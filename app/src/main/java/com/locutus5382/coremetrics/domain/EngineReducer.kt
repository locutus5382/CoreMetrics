package com.locutus5382.coremetrics.domain

/**
 * Deterministic state transitions. No Android imports, disk access, timers or callbacks.
 * Effects are interpreted by a *future* serialized :monitor coordinator; their results
 * return as EngineEvent values. This reducer does not replace RecordingService in M2-A.
 */
internal object EngineReducer {
    private const val COMMAND_HISTORY_LIMIT = 32

    fun reduce(current: EngineState, event: EngineEvent): EngineTransition {
        val raw = when (event) {
            is EngineEvent.Command -> command(current, event.value)
            is EngineEvent.SessionOpened -> opened(current, event)
            is EngineEvent.SessionOpenFailed -> openFailed(current, event)
            is EngineEvent.StopIntentPersisted -> stopPersisted(current, event)
            is EngineEvent.StopIntentFailed -> stopFailed(current, event)
            is EngineEvent.SessionFinalized -> finalized(current, event)
            is EngineEvent.SessionFinalizeFailed -> finalizeFailed(current, event)
            is EngineEvent.OverlayAttached -> attached(current, event.operationId)
            is EngineEvent.OverlayAttachFailed -> attachFailed(current, event)
            is EngineEvent.OverlayDetached -> detached(current, event.operationId)
            is EngineEvent.OverlayDetachFailed -> detachFailed(current, event)
            is EngineEvent.OverlayPermissionChanged -> permission(current, event.granted)
            is EngineEvent.Reconcile -> reconcile(current, event)
            is EngineEvent.SessionResumed -> resumed(current, event.sessionId)
            is EngineEvent.InterruptedSessionClosed -> interruptedClosed(current, event.sessionId)
        }
        return if (raw.state == current) raw
        else raw.copy(state = raw.state.copy(sequence = current.sequence + 1))
    }

    private fun command(s: EngineState, command: EngineCommand): EngineTransition {
        // Commands are generated by platform entry points. A re-delivered intent is harmless.
        if (command.id.isBlank()) return EngineTransition(s)
        if (command.id in s.recentCommandIds) return EngineTransition(s)
        val accepted = s.copy(recentCommandIds =
            (s.recentCommandIds + command.id).takeLast(COMMAND_HISTORY_LIMIT))
        return when (command) {
            is EngineCommand.Start -> start(accepted, command)
            is EngineCommand.Stop -> stop(accepted, command)
            is EngineCommand.RetryFinalization -> retryFinalization(accepted, command)
            is EngineCommand.SetOverlayVisible -> overlayCommand(accepted, command)
            is EngineCommand.SetHudPresentation -> EngineTransition(accepted.copy(
                presentation = command.value, lastAck = ack(command.id, CommandOutcome.ACCEPTED)))
        }
    }

    private fun start(s: EngineState, c: EngineCommand.Start): EngineTransition =
        if (s.recording is RecordingState.Idle ||
            s.recording is RecordingState.Failed && s.recording.sessionId == null) {
            EngineTransition(
                s.copy(recording = RecordingState.Starting(c.id, c.profileId),
                    lastAck = ack(c.id, CommandOutcome.ACCEPTED)),
                listOf(EngineEffect.OpenSession(c.id, c.profileId)),
            )
        } else EngineTransition(s.copy(lastAck = ack(c.id, CommandOutcome.IGNORED, "ACTIVE_OR_PENDING")))

    private fun stop(s: EngineState, c: EngineCommand.Stop): EngineTransition = when (val r = s.recording) {
        is RecordingState.Starting -> EngineTransition(s.copy(
            recording = r.copy(pendingStopId = r.pendingStopId ?: c.id),
            lastAck = ack(c.id, CommandOutcome.ACCEPTED)))
        is RecordingState.Recording -> stopRequested(s, r.sessionId, c.id, c.reason)
        is RecordingState.Recovering -> stopRequested(s, r.sessionId, c.id, c.reason)
        is RecordingState.StopRequested -> {
            // Explicit retry is allowed only after the prior persistence attempt failed.
            if (r.persistError != null) EngineTransition(s.copy(
                recording = r.copy(persistError = null),
                lastAck = ack(c.id, CommandOutcome.ACCEPTED)),
                listOf(EngineEffect.PersistStopIntent(r.sessionId, r.stopId)))
            else EngineTransition(s.copy(lastAck = ack(c.id, CommandOutcome.IGNORED, "STOP_PENDING")))
        }
        else -> EngineTransition(s.copy(lastAck = ack(c.id, CommandOutcome.IGNORED, "NOT_RECORDING")))
    }

    private fun retryFinalization(s: EngineState, c: EngineCommand.RetryFinalization): EngineTransition {
        val r = s.recording as? RecordingState.FinalizeFailed
            ?: return EngineTransition(s.copy(lastAck = ack(c.id, CommandOutcome.IGNORED, "NO_FAILED_FINALIZATION")))
        return EngineTransition(s.copy(
            recording = RecordingState.Finalizing(r.sessionId, r.stopId, r.reason),
            lastAck = ack(c.id, CommandOutcome.ACCEPTED)),
            listOf(EngineEffect.FinalizeSession(r.sessionId, r.stopId, r.reason)))
    }

    private fun stopRequested(s: EngineState, sessionId: Long, stopId: String, reason: StopReason) =
        EngineTransition(s.copy(recording = RecordingState.StopRequested(sessionId, stopId, reason),
            lastAck = ack(stopId, CommandOutcome.ACCEPTED)), listOf(
            EngineEffect.PauseSampling(sessionId),
            EngineEffect.PersistStopIntent(sessionId, stopId),
        ))

    private fun opened(s: EngineState, e: EngineEvent.SessionOpened): EngineTransition {
        val r = s.recording as? RecordingState.Starting ?: return EngineTransition(s)
        if (r.startId != e.startId || e.sessionId <= 0) return EngineTransition(s)
        return if (r.pendingStopId != null) stopRequested(s, e.sessionId, r.pendingStopId, StopReason.USER)
        else EngineTransition(s.copy(recording = RecordingState.Recording(e.sessionId,
            e.startedAtElapsedMs, r.profileId)))
    }

    private fun openFailed(s: EngineState, e: EngineEvent.SessionOpenFailed): EngineTransition {
        val r = s.recording as? RecordingState.Starting ?: return EngineTransition(s)
        if (r.startId != e.startId) return EngineTransition(s)
        return EngineTransition(s.copy(recording = RecordingState.Failed(e.reason)))
    }

    private fun stopPersisted(s: EngineState, e: EngineEvent.StopIntentPersisted): EngineTransition {
        val r = s.recording as? RecordingState.StopRequested ?: return EngineTransition(s)
        if (r.sessionId != e.sessionId || r.stopId != e.stopId) return EngineTransition(s)
        return EngineTransition(s.copy(recording = RecordingState.Finalizing(r.sessionId, r.stopId,
            r.reason)), listOf(EngineEffect.FinalizeSession(r.sessionId, r.stopId, r.reason)))
    }

    private fun stopFailed(s: EngineState, e: EngineEvent.StopIntentFailed): EngineTransition {
        val r = s.recording as? RecordingState.StopRequested ?: return EngineTransition(s)
        if (r.sessionId != e.sessionId || r.stopId != e.stopId) return EngineTransition(s)
        return EngineTransition(s.copy(recording = r.copy(persistError = e.reason)))
    }

    private fun finalized(s: EngineState, e: EngineEvent.SessionFinalized): EngineTransition {
        val r = s.recording as? RecordingState.Finalizing ?: return EngineTransition(s)
        if (r.sessionId != e.sessionId || r.stopId != e.stopId) return EngineTransition(s)
        return EngineTransition(s.copy(recording = RecordingState.Idle))
    }

    private fun finalizeFailed(s: EngineState, e: EngineEvent.SessionFinalizeFailed): EngineTransition {
        val r = s.recording as? RecordingState.Finalizing ?: return EngineTransition(s)
        if (r.sessionId != e.sessionId || r.stopId != e.stopId) return EngineTransition(s)
        // Durable STOP is already saved; never resume recording. A later retry may finalize.
        return EngineTransition(s.copy(recording = RecordingState.FinalizeFailed(
            r.sessionId, r.stopId, r.reason, e.reason)))
    }

    private fun overlayCommand(s: EngineState, c: EngineCommand.SetOverlayVisible): EngineTransition {
        val current = s.copy(wantsOverlay = c.visible, lastAck = ack(c.id, CommandOutcome.ACCEPTED))
        if (!c.visible) return when (current.overlay) {
            is OverlayAttachment.Attached -> requestDetach(current)
            is OverlayAttachment.CleanupRequired -> EngineTransition(current,
                listOf(EngineEffect.DetachOverlay(current.overlay.operationId)))
            is OverlayAttachment.Attaching, is OverlayAttachment.Detaching -> EngineTransition(current)
            else -> EngineTransition(current.copy(overlay = OverlayAttachment.Detached))
        }
        if (current.overlay is OverlayAttachment.CleanupRequired) return EngineTransition(current)
        if (!current.hasOverlayPermission) return EngineTransition(current.copy(
            overlay = OverlayAttachment.Blocked("PERMISSION_MISSING")))
        return when (current.overlay) {
            is OverlayAttachment.Detached, is OverlayAttachment.Blocked -> requestAttach(current)
            else -> EngineTransition(current)
        }
    }

    private fun permission(s: EngineState, granted: Boolean): EngineTransition {
        val updated = s.copy(hasOverlayPermission = granted)
        if (granted) return if (updated.wantsOverlay &&
            (updated.overlay is OverlayAttachment.Detached || updated.overlay is OverlayAttachment.Blocked))
            requestAttach(updated) else EngineTransition(updated)
        return when (updated.overlay) {
            is OverlayAttachment.Attached -> requestDetach(updated)
            is OverlayAttachment.Detached, is OverlayAttachment.Blocked -> EngineTransition(updated.copy(
                overlay = if (updated.wantsOverlay) OverlayAttachment.Blocked("PERMISSION_MISSING")
                else OverlayAttachment.Detached))
            else -> EngineTransition(updated) // Wait for in-flight attachment/detachment completion.
        }
    }

    private fun requestAttach(s: EngineState): EngineTransition {
        val id = s.nextOverlayOperation
        return EngineTransition(s.copy(overlay = OverlayAttachment.Attaching(id),
            nextOverlayOperation = id + 1), listOf(EngineEffect.AttachOverlay(id)))
    }

    private fun requestDetach(s: EngineState): EngineTransition {
        val id = s.nextOverlayOperation
        return EngineTransition(s.copy(overlay = OverlayAttachment.Detaching(id),
            nextOverlayOperation = id + 1), listOf(EngineEffect.DetachOverlay(id)))
    }

    private fun attached(s: EngineState, id: Long): EngineTransition {
        val attaching = s.overlay as? OverlayAttachment.Attaching ?: return EngineTransition(s)
        if (attaching.operationId != id) return EngineTransition(s)
        return if (!s.wantsOverlay || !s.hasOverlayPermission) requestDetach(s)
        else EngineTransition(s.copy(overlay = OverlayAttachment.Attached))
    }

    private fun attachFailed(s: EngineState, e: EngineEvent.OverlayAttachFailed): EngineTransition {
        val r = s.overlay as? OverlayAttachment.Attaching ?: return EngineTransition(s)
        if (r.operationId != e.operationId) return EngineTransition(s)
        return EngineTransition(s.copy(overlay = if (s.wantsOverlay)
            OverlayAttachment.Blocked(e.reason) else OverlayAttachment.Detached))
    }

    private fun detached(s: EngineState, id: Long): EngineTransition {
        val expectedId = when (val o = s.overlay) {
            is OverlayAttachment.Detaching -> o.operationId
            is OverlayAttachment.CleanupRequired -> o.operationId
            else -> return EngineTransition(s)
        }
        if (expectedId != id) return EngineTransition(s)
        return if (s.wantsOverlay && s.hasOverlayPermission) requestAttach(s)
        else EngineTransition(s.copy(overlay = if (s.wantsOverlay)
            OverlayAttachment.Blocked("PERMISSION_MISSING") else OverlayAttachment.Detached))
    }

    private fun detachFailed(s: EngineState, e: EngineEvent.OverlayDetachFailed): EngineTransition {
        val r = s.overlay as? OverlayAttachment.Detaching ?: return EngineTransition(s)
        if (r.operationId != e.operationId) return EngineTransition(s)
        // Never assume the view was removed; an automatic reattach could duplicate it.
        return EngineTransition(s.copy(overlay = OverlayAttachment.CleanupRequired(
            r.operationId, e.reason)))
    }

    private fun reconcile(s: EngineState, e: EngineEvent.Reconcile): EngineTransition {
        // Engine start only. The platform reconciler, NOT a stale UI snapshot, creates this event.
        if (s.recording !is RecordingState.Idle) return EngineTransition(s)
        val id = e.sessionId?.takeIf { it > 0 } ?: return EngineTransition(s)
        return when {
            e.stopIntentPersisted -> EngineTransition(s.copy(recording =
                RecordingState.Finalizing(id, "recovery-stop-$id", StopReason.USER)),
                listOf(EngineEffect.FinalizeSession(id, "recovery-stop-$id", StopReason.USER)))
            e.leaseEligible -> EngineTransition(s.copy(recording =
                RecordingState.Recovering(id, e.startedAtElapsedMs, e.profileId),
                dataIssues = s.dataIssues + DataIssue.RECOVERED + DataIssue.SAMPLE_GAP),
                listOf(EngineEffect.ResumeSession(id)))
            else -> EngineTransition(s.copy(recording =
                RecordingState.Finalizing(id, "recovery-interrupted-$id", StopReason.INTERRUPTED)),
                listOf(EngineEffect.CloseInterruptedSession(id)))
        }
    }

    private fun resumed(s: EngineState, id: Long): EngineTransition {
        val r = s.recording as? RecordingState.Recovering ?: return EngineTransition(s)
        if (r.sessionId != id) return EngineTransition(s)
        return EngineTransition(s.copy(recording = RecordingState.Recording(id,
            r.startedAtElapsedMs, r.profileId)))
    }

    private fun interruptedClosed(s: EngineState, id: Long): EngineTransition {
        val r = s.recording as? RecordingState.Finalizing ?: return EngineTransition(s)
        if (r.sessionId != id || r.reason != StopReason.INTERRUPTED) return EngineTransition(s)
        return EngineTransition(s.copy(recording = RecordingState.Idle))
    }

    private fun ack(id: String, outcome: CommandOutcome, reason: String? = null) =
        CommandAck(id, outcome, reason)
}
